/* ── the translate function ─────────────────────────────────────────── */

/** Registered notices the server writes in English — matched back to a template. */
const NOTICE_FORMS = [
  { re: /^New episode of (.+) is out now\.$/, key: 'New episode of {name} is out now.' },
  { re: /^New chapter of (.+) is out now\.$/, key: 'New chapter of {name} is out now.' },
  { re: /^New novel added: (.+)$/, key: 'New novel added: {name}' },
  { re: /^Welcome to THE FLASH\. Your library of stories awaits\.$/, key: 'Welcome to THE FLASH. Your library of stories awaits.' },
];

/** Fill {placeholders} without touching any other braces. */
function interpolate(text, vars) {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (whole, name) => (name in vars ? String(vars[name]) : whole));
}

export function isLang(code) {
  return LANGS.some((l) => l.code === code);
}

/**
 * Translate one English interface string. Unknown keys fall through unchanged,
 * which is what keeps a half-finished translation usable rather than broken.
 */
export function translate(lang, key, vars) {
  const table = STRINGS[lang];
  const out = (table && table[key]) || key;
  return interpolate(out, vars);
}

/**
 * Rewrite a server-generated notification message in the active language while
 * leaving the title name inside it untouched.
 */
export function translateNotice(lang, message) {
  if (lang === DEFAULT_LANG) return message;
  const text = String(message || '');
  for (const { re, key } of NOTICE_FORMS) {
    const m = text.match(re);
    if (m) return translate(lang, key, { name: m[1] });
  }
  return text;
}
