// THE FLASH — interface translations.
//
// Only the *interface* is translated. Catalogue content — title names, novel
// names, chapter text, episode names, genres, authors, comments — is served
// exactly as written, in whatever language it was authored in.
//
// The keys are the English interface text itself. That choice buys graceful
// degradation: a string nobody has translated yet renders in English instead of
// rendering blank, and `npm test` fails if a key used in the UI is missing from
// any language, so gaps cannot reach the user silently.

